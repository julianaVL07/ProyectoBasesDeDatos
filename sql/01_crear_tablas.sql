-- ============================ MÓDULO ENTIDADES ============================

CREATE TABLE TDepartamento (
    DCodigo  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DNombre  VARCHAR2(60) NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (DCodigo),
    CONSTRAINT uq_departamento_nombre UNIQUE (DNombre)
);

CREATE TABLE TCiudad (
    CCodigo  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CNombre  VARCHAR2(60) NOT NULL,
    DCodigo  NUMBER NOT NULL,
    CONSTRAINT pk_ciudad PRIMARY KEY (CCodigo),
    CONSTRAINT fk_ciudad_departamento FOREIGN KEY (DCodigo) REFERENCES TDepartamento (DCodigo)
);

CREATE TABLE TCategoria (
    CaCodigo       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CaNombre       VARCHAR2(60)  NOT NULL,
    CaDescripcion  VARCHAR2(200),
    CONSTRAINT pk_categoria PRIMARY KEY (CaCodigo),
    CONSTRAINT uq_categoria_nombre UNIQUE (CaNombre)
);

CREATE TABLE TProveedor (
    PCodigo     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PNit        VARCHAR2(20)  NOT NULL,
    PNombre     VARCHAR2(100) NOT NULL,
    PDireccion  VARCHAR2(120),
    PCorreo     VARCHAR2(100),
    PTelefono   VARCHAR2(20),
    PActivo     NUMBER(1) DEFAULT 1 NOT NULL,
    CCodigo     NUMBER NOT NULL,
    CONSTRAINT pk_proveedor PRIMARY KEY (PCodigo),
    CONSTRAINT uq_proveedor_nit UNIQUE (PNit),
    CONSTRAINT ck_proveedor_activo CHECK (PActivo IN (0, 1)),
    CONSTRAINT fk_proveedor_ciudad FOREIGN KEY (CCodigo) REFERENCES TCiudad (CCodigo)
);

CREATE TABLE TProducto (
    PrCodigo       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PrNombre       VARCHAR2(100) NOT NULL,
    PrDescripcion  VARCHAR2(250),
    PrPrecioBase   NUMBER(12,2)  NOT NULL,
    PrStock        NUMBER(8)     DEFAULT 0 NOT NULL,
    CaCodigo       NUMBER NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (PrCodigo),
    CONSTRAINT ck_producto_precio CHECK (PrPrecioBase >= 0),
    CONSTRAINT ck_producto_stock  CHECK (PrStock >= 0),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (CaCodigo) REFERENCES TCategoria (CaCodigo)
);

-- ============================ TRANSACCIONES ==============================
-- Entidad asociativa: resuelve la relación N:M entre Proveedor y Producto.

CREATE TABLE TSuministro (
    SCodigo        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SDiasEntrega   NUMBER(3)    NOT NULL,
    SPrecio        NUMBER(12,2) NOT NULL,
    PCodigo        NUMBER NOT NULL,
    PrCodigo       NUMBER NOT NULL,
    CONSTRAINT pk_suministro PRIMARY KEY (SCodigo),
    CONSTRAINT uq_suministro_prov_prod UNIQUE (PCodigo, PrCodigo),
    CONSTRAINT ck_suministro_dias   CHECK (SDiasEntrega >= 0),
    CONSTRAINT ck_suministro_precio CHECK (SPrecio >= 0),
    CONSTRAINT fk_suministro_proveedor FOREIGN KEY (PCodigo)  REFERENCES TProveedor (PCodigo),
    CONSTRAINT fk_suministro_producto  FOREIGN KEY (PrCodigo) REFERENCES TProducto (PrCodigo)
);

-- ============================ MÓDULO AUDITORÍA ===========================

CREATE TABLE TRol (
    RCodigo       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RNombre       VARCHAR2(30) NOT NULL,
    RDescripcion  VARCHAR2(150),
    CONSTRAINT pk_rol PRIMARY KEY (RCodigo),
    CONSTRAINT uq_rol_nombre UNIQUE (RNombre)
);

CREATE TABLE TUsuario (
    UCodigo          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    UNombreUsuario   VARCHAR2(30)  NOT NULL,
    -- Nombre sin tilde (UContrasena) para evitar problemas de codificación.
    -- Guardar el HASH de la clave (SHA-256 en hexadecimal = 64 caracteres), nunca el texto plano.
    UContrasena      VARCHAR2(100) NOT NULL,
    UActivo          NUMBER(1) DEFAULT 1 NOT NULL,
    UFechaCreacion   DATE DEFAULT SYSDATE NOT NULL,
    UNombreCompleto  VARCHAR2(100) NOT NULL,
    RCodigo          NUMBER NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (UCodigo),
    CONSTRAINT uq_usuario_nombre UNIQUE (UNombreUsuario),
    CONSTRAINT ck_usuario_activo CHECK (UActivo IN (0, 1)),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (RCodigo) REFERENCES TRol (RCodigo)
);

-- Solo puede existir UN Administrador (RCodigo = 1, ver 02_datos_iniciales.sql).
-- Índice único basado en función: los usuarios no-admin dan NULL y no cuentan.
CREATE UNIQUE INDEX ux_usuario_unico_admin
    ON TUsuario (CASE WHEN RCodigo = 1 THEN 1 END);

-- Fecha y hora separadas, tal como aparecen en el diagrama Entidad-Relación.
-- La hora se guarda como texto 'HH24:MI:SS' (p. ej. '14:05:09').
CREATE TABLE TBitacora (
    BCodigo        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BFechaIngreso  DATE        DEFAULT TRUNC(SYSDATE)                NOT NULL,
    BHoraIngreso   VARCHAR2(8) DEFAULT TO_CHAR(SYSDATE, 'HH24:MI:SS') NOT NULL,
    BFechaSalida   DATE,          -- NULL mientras la sesión siga abierta
    BHoraSalida    VARCHAR2(8),   -- NULL mientras la sesión siga abierta
    UCodigo        NUMBER NOT NULL,
    CONSTRAINT pk_bitacora PRIMARY KEY (BCodigo),
    -- Las fechas guardan solo el día (sin hora).
    CONSTRAINT ck_bitacora_fecha_ing CHECK (BFechaIngreso = TRUNC(BFechaIngreso)),
    CONSTRAINT ck_bitacora_fecha_sal CHECK (BFechaSalida IS NULL OR BFechaSalida = TRUNC(BFechaSalida)),
    -- Formato de hora válido 00:00:00 .. 23:59:59
    CONSTRAINT ck_bitacora_hora_ing CHECK (
        REGEXP_LIKE(BHoraIngreso, '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')),
    CONSTRAINT ck_bitacora_hora_sal CHECK (BHoraSalida IS NULL OR
        REGEXP_LIKE(BHoraSalida, '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')),
    -- Fecha y hora de salida van juntas: ambas NULL o ambas con valor.
    CONSTRAINT ck_bitacora_salida_completa CHECK (
        (BFechaSalida IS NULL AND BHoraSalida IS NULL) OR
        (BFechaSalida IS NOT NULL AND BHoraSalida IS NOT NULL)),
    -- La salida no puede ser anterior al ingreso ('HH24:MI:SS' se compara bien como texto).
    CONSTRAINT ck_bitacora_orden CHECK (
        BFechaSalida IS NULL OR BFechaSalida > BFechaIngreso OR
        (BFechaSalida = BFechaIngreso AND BHoraSalida >= BHoraIngreso)),
    CONSTRAINT fk_bitacora_usuario FOREIGN KEY (UCodigo) REFERENCES TUsuario (UCodigo)
);

-- Índices en llaves foráneas (Oracle no los crea solo)
CREATE INDEX ix_ciudad_dep      ON TCiudad (DCodigo);
CREATE INDEX ix_proveedor_ciu   ON TProveedor (CCodigo);
CREATE INDEX ix_producto_cat    ON TProducto (CaCodigo);
CREATE INDEX ix_suministro_prod ON TSuministro (PrCodigo);
CREATE INDEX ix_usuario_rol     ON TUsuario (RCodigo);
CREATE INDEX ix_bitacora_usu    ON TBitacora (UCodigo);
