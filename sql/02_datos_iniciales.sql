-- Como pusimos los códigos a mano, la IDENTITY debe continuar después del mayor (4, 5, ...).
ALTER TABLE TRol MODIFY RCodigo GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);

-- Administrador inicial (el único).  Usuario: admin   Clave: Admin123*
-- ¡Cambiar la clave desde la aplicación después del primer ingreso!
-- La clave se guarda como SHA-256 en hexadecimal minúscula, igual que util/Seguridad.java.
INSERT INTO TUsuario (UNombreUsuario, UContrasena, UNombreCompleto, RCodigo)
VALUES ('admin',
        LOWER(RAWTOHEX(STANDARD_HASH('Admin123*', 'SHA256'))),
        'Administrador del sistema',
        1);

